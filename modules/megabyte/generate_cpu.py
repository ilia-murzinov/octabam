#!/usr/bin/env python3
"""Generate the freestanding ColdFire unit for Megabyte (Tape Echo pattern)."""
import pathlib
import re
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
FLAGS = ['-mcpu=54454', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin',
         '-fno-common', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer']


def gcc_version():
    out = subprocess.run(['m68k-elf-gcc', '--version'], capture_output=True, text=True, check=True).stdout
    return out.splitlines()[0].split()[-1]


def written_with(source):
    m = re.match(r'\| Generated by generate_cpu\.py \(m68k-elf-gcc ([\d.]+)\)', source)
    return m.group(1) if m else None


def generate():
    with tempfile.TemporaryDirectory() as td:
        asm = pathlib.Path(td) / 'cpu.s'
        subprocess.run(['m68k-elf-gcc', *FLAGS, '-S', 'modules/megabyte/cpu.c',
                        '-o', str(asm)], cwd=ROOT, check=True)
        source = (f'| Generated by generate_cpu.py (m68k-elf-gcc {gcc_version()}); '
                  f'edit cpu.c / cpu_hooks.s.\n'
                  + re.sub(r'(?m)^\tjra (mb_\w+)$', r'\tjmp \1', asm.read_text())
                  + '\n' + (HERE / 'cpu_hooks.s').read_text())
        if '*8)' in source:
            raise RuntimeError('scaled-*8 ColdFire address mode is hardware-unsafe (Vec 03)')
        asm.write_text(source)
        binaries = []
        for cpu in ('54454', '5475'):
            obj = pathlib.Path(td) / f'{cpu}.o'
            binary = pathlib.Path(td) / f'{cpu}.bin'
            subprocess.run(['m68k-elf-as', f'-mcpu={cpu}', str(asm), '-o', str(obj)], check=True)
            subprocess.run(['m68k-elf-objcopy', '-O', 'binary', '-j', '.text',
                            str(obj), str(binary)], check=True)
            binaries.append(binary.read_bytes())
        if binaries[0] != binaries[1]:
            raise RuntimeError('54454 machine code differs from platform ISA-B encoding')
        return source


if __name__ == '__main__':
    source = generate()
    dest = HERE / 'cpu.s'
    if '--check' in sys.argv:
        committed = dest.read_text() if dest.exists() else ''
        recorded, local = written_with(committed), gcc_version()
        if not dest.exists():
            sys.exit('Megabyte cpu.s is missing: run modules/megabyte/generate_cpu.py')
        if recorded != local:
            print(f'  [SKIP] Megabyte cpu.s was written by m68k-elf-gcc '
                  f'{recorded or "an unrecorded version"}; this machine has {local}')
            sys.exit(0)
        if committed != source:
            sys.exit('Megabyte cpu.s is stale: run modules/megabyte/generate_cpu.py')
        print('  [PASS] Megabyte cpu.s matches generate_cpu.py')
        sys.exit(0)
    dest.write_text(source)
    print(f'wrote {dest} ({len(source)} bytes)')
